interface RawPost {
  title: string;
  description: string;
  link: string;
  date?: string;
  author?: string;
}

interface FeedConfig {
  name: string;
  url: string;
}

const MONTH_NAMES = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function formatNewsDate(dateInput?: string | Date): string {
  const d = dateInput ? new Date(dateInput) : new Date();
  if (isNaN(d.getTime())) {
    const now = new Date();
    return `${MONTH_NAMES[now.getMonth()]} ${now.getFullYear()}`;
  }
  return `${MONTH_NAMES[d.getMonth()]} ${d.getFullYear()}`;
}

function cleanText(text: string): string {
  return text
    .replace(/<[^>]*>/g, "") // strip HTML tags
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .trim();
}

/**
 * Normalizes URL for deduplication by removing hash fragments like #author=...
 */
function getBaseLink(link?: string): string {
  if (!link) return "";
  return link.split("#author=")[0].split("?author=")[0].trim().toLowerCase();
}

/**
 * Parses RSS / Atom XML feeds commonly generated by RSS.app, FetchRSS,
 * or custom bridges for LinkedIn feeds.
 */
function parseRssFeed(xml: string, authorName?: string): RawPost[] {
  const items: RawPost[] = [];
  
  const itemRegex = /<(?:item|entry)[\s>]([\s\S]*?)<\/(?:item|entry)>/gi;
  let match;

  while ((match = itemRegex.exec(xml)) !== null) {
    const itemContent = match[1];

    // Extract Title
    const titleMatch = /<title[^>]*>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/title>/i.exec(itemContent);
    // Extract Link
    const linkMatch =
      /<link[^>]*href=["']([^"']+)["']/i.exec(itemContent) ||
      /<link[^>]*>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/link>/i.exec(itemContent);
    // Extract Description / Content
    const descMatch =
      /<content:encoded[^>]*>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/content:encoded>/i.exec(itemContent) ||
      /<description[^>]*>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/description>/i.exec(itemContent) ||
      /<summary[^>]*>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/summary>/i.exec(itemContent);
    // Extract PubDate
    const dateMatch =
      /<pubDate[^>]*>([\s\S]*?)<\/pubDate>/i.exec(itemContent) ||
      /<updated[^>]*>([\s\S]*?)<\/updated>/i.exec(itemContent) ||
      /<dc:date[^>]*>([\s\S]*?)<\/dc:date>/i.exec(itemContent);

    // Try extracting author if present inside XML item
    const authorMatch =
      /<dc:creator[^>]*>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/dc:creator>/i.exec(itemContent) ||
      /<author[^>]*>[\s\S]*?<name>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/name>/i.exec(itemContent);

    const rawTitle = titleMatch ? cleanText(titleMatch[1]) : "";
    const rawDesc = descMatch ? cleanText(descMatch[1]) : "";
    let rawLink = linkMatch ? linkMatch[1].trim() : "";
    const rawDate = dateMatch ? dateMatch[1].trim() : "";
    const itemAuthor = authorName || (authorMatch ? cleanText(authorMatch[1]) : undefined);

    if (rawLink || rawTitle || rawDesc) {
      let title = rawTitle;
      if (!title || title.length < 5) {
        title = rawDesc.slice(0, 80).split(/[.!?\n]/)[0].trim() || (itemAuthor ? `${itemAuthor} on LinkedIn` : "LinkedIn Team Update");
      }

      if (title.length > 100) {
        title = title.substring(0, 97) + "...";
      }

      // Append author hash to link so client components can attribute the post
      if (itemAuthor && rawLink && !rawLink.includes("#author=")) {
        rawLink = `${rawLink}#author=${encodeURIComponent(itemAuthor)}`;
      }

      items.push({
        title,
        description: rawDesc || rawTitle || "Read more about our latest research update on LinkedIn.",
        link: rawLink,
        date: formatNewsDate(rawDate),
        author: itemAuthor,
      });
    }
  }

  return items;
}

/**
 * Fetch and extract OpenGraph info from a single LinkedIn post URL
 */
async function fetchPostMetadata(postUrl: string, authorName?: string): Promise<RawPost | null> {
  try {
    const res = await fetch(postUrl, {
      headers: {
        "User-Agent": "Mozilla/5.0 (compatible; Googlebot/2.1; +http://www.google.com/bot.html)",
        Accept: "text/html,application/xhtml+xml",
      },
    });

    if (!res.ok) {
      console.warn(`Failed to fetch URL ${postUrl}: HTTP ${res.status}`);
      return null;
    }

    const html = await res.text();
    const titleMatch =
      /<meta property=["']og:title["'] content=["']([^"']+)["']/i.exec(html) ||
      /<title>([^<]+)<\/title>/i.exec(html);
    const descMatch =
      /<meta property=["']og:description["'] content=["']([^"']+)["']/i.exec(html) ||
      /<meta name=["']description["'] content=["']([^"']+)["']/i.exec(html);

    const rawTitle = titleMatch ? cleanText(titleMatch[1]) : (authorName ? `${authorName} on LinkedIn` : "Team Update on LinkedIn");
    const rawDesc = descMatch ? cleanText(descMatch[1]) : "";

    let finalLink = postUrl;
    if (authorName && !finalLink.includes("#author=")) {
      finalLink = `${finalLink}#author=${encodeURIComponent(authorName)}`;
    }

    return {
      title: rawTitle.substring(0, 100),
      description: rawDesc || "Check out our latest update on LinkedIn.",
      link: finalLink,
      date: formatNewsDate(),
      author: authorName,
    };
  } catch (err: any) {
    console.error(`Error scraping post ${postUrl}:`, err.message);
    return null;
  }
}

/**
 * Parses multiple feeds from LINKEDIN_FEEDS env var.
 * Supports JSON: [{"name": "Deepika", "url": "https://..."}, {"name": "Vikas Kumar", "url": "https://..."}]
 * Or delimiter: "Deepika=https://...,Vikas Kumar=https://..."
 */
async function parseFeedConfigs(): Promise<FeedConfig[]> {
  const configs: FeedConfig[] = [];
  const registeredUrls = new Set<string>();

  // 1. Fetch live feeds stored directly in the Supabase team_members database table!
  try {
    console.log("Checking Supabase team_members table for configured feeds...");
    const { data: dbMembers, error: dbErr } = await supabase
      .from("team_members")
      .select("name, links");

    if (dbErr) {
      console.warn("  Could not fetch team_members:", dbErr.message);
    } else if (dbMembers) {
      for (const member of dbMembers) {
        const feedUrl = member.links?.linkedinFeed || member.links?.rssFeed;
        if (
          feedUrl &&
          typeof feedUrl === "string" &&
          feedUrl.trim() &&
          !feedUrl.includes("rsshub.app/linkedin/post")
        ) {
          const cleanUrl = feedUrl.trim();
          console.log(`  ✓ Found custom feed for ${member.name}: ${cleanUrl}`);
          configs.push({
            name: member.name,
            url: cleanUrl,
          });
          registeredUrls.add(cleanUrl.toLowerCase());
        }
      }
    }
  } catch (err: any) {
    console.warn("  Database team feed check error:", err.message);
  }

  // 2. Also check environment variable LINKEDIN_FEEDS
  const rawFeeds = process.env.LINKEDIN_FEEDS;
  if (rawFeeds) {
    try {
      const parsed = JSON.parse(rawFeeds);
      if (Array.isArray(parsed)) {
        for (const item of parsed) {
          if (item.url && item.url.trim()) {
            const cleanUrl = item.url.trim();
            if (!registeredUrls.has(cleanUrl.toLowerCase())) {
              configs.push({
                name: item.name || "InSilicoVida Team",
                url: cleanUrl,
              });
              registeredUrls.add(cleanUrl.toLowerCase());
            }
          }
        }
      }
    } catch {
      // Parse format "Name=URL,Name=URL"
      const entries = rawFeeds.split(",");
      for (const entry of entries) {
        const parts = entry.split("=");
        if (parts.length >= 2) {
          const name = parts[0].trim();
          const url = parts.slice(1).join("=").trim();
          if (url && !registeredUrls.has(url.toLowerCase())) {
            configs.push({ name, url });
            registeredUrls.add(url.toLowerCase());
          }
        }
      }
    }
  }

  // 3. If no env var or DB feeds, check local linkedin_feeds.json
  if (configs.length === 0) {
    try {
      const localConfigPath = path.resolve(process.cwd(), "linkedin_feeds.json");
      if (fs.existsSync(localConfigPath)) {
        const fileContent = fs.readFileSync(localConfigPath, "utf-8");
        const parsed = JSON.parse(fileContent);
        if (Array.isArray(parsed)) {
          for (const item of parsed) {
            if (item.url && item.url.trim()) {
              const cleanUrl = item.url.trim();
              if (!registeredUrls.has(cleanUrl.toLowerCase())) {
                configs.push({
                  name: item.name || "InSilicoVida Team",
                  url: cleanUrl,
                });
                registeredUrls.add(cleanUrl.toLowerCase());
              }
            }
          }
        }
      }
    } catch (e: any) {
      console.warn("Could not read linkedin_feeds.json:", e.message);
    }
  }

  // 4. Fallback to single feed env vars if configs is empty
  const singleFeedUrl = process.env.LINKEDIN_FEED_URL || process.env.LINKEDIN_RSS_URL;
  if (singleFeedUrl && configs.length === 0) {
    configs.push({
      name: process.env.LINKEDIN_AUTHOR || "InSilicoVida Lab",
      url: singleFeedUrl.trim(),
    });
  }

  return configs;
}

/**
 * Automated headless scraper using Playwright to extract recent posts from team member profiles.
 * Authenticates using the LINKEDIN_LI_AT session cookie to bypass login barriers.
 */
async function scrapeLinkedInTeamPosts(
  members: Array<{ name: string; linkedinUrl: string }>,
  liAtCookie: string
): Promise<RawPost[]> {
  console.log(`\n==========================================`);
  console.log(`Starting Headless Scraper for ${members.length} Member(s)`);
  console.log(`==========================================\n`);

  const posts: RawPost[] = [];
  let browser;

  try {
    browser = await chromium.launch({
      headless: true,
      args: ["--no-sandbox", "--disable-setuid-sandbox", "--disable-dev-shm-usage"],
    });

    const context = await browser.newContext({
      userAgent:
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/123.0.0.0 Safari/537.36",
      viewport: { width: 1280, height: 900 },
    });

    // Inject session cookie into context
    await context.addCookies([
      {
        name: "li_at",
        value: liAtCookie.trim(),
        domain: ".linkedin.com",
        path: "/",
        httpOnly: true,
        secure: true,
      },
    ]);

    const page = await context.newPage();

    for (const member of members) {
      const username = extractLinkedInUsername(member.linkedinUrl);
      if (!username) continue;

      const activityUrl = `https://www.linkedin.com/in/${encodeURIComponent(username)}/recent-activity/all/`;
      console.log(`- Scraping posts for "${member.name}" (${username})...`);

      try {
        await page.goto(activityUrl, { waitUntil: "domcontentloaded", timeout: 30000 });
        await page.waitForTimeout(3500);

        // Check if session expired or blocked
        if (page.url().includes("/login") || page.url().includes("/checkpoint/")) {
          console.warn("  ⚠️ Warning: LinkedIn session cookie expired or security checkpoint encountered.");
          console.warn("  Please update the LINKEDIN_LI_AT secret in GitHub repository settings.");
          break;
        }

        const extracted = await page.evaluate((authorName) => {
          const results: Array<{ text: string; link: string }> = [];

          const postContainers = document.querySelectorAll(
            '.feed-shared-update-v2, div[data-urn*="urn:li:activity:"], div[data-id*="urn:li:activity:"], article'
          );

          postContainers.forEach((container, idx) => {
            if (idx >= 3) return; // Keep top 3 most recent posts per member

            // 1. Try to find post direct URL / URN
            let postLink = "";
            const urn =
              container.getAttribute("data-urn") ||
              container.getAttribute("data-id") ||
              "";

            if (urn && urn.includes("urn:li:activity:")) {
              const actId = urn.split("urn:li:activity:")[1]?.split(/[\s&?;'"]/)[0];
              if (actId) {
                postLink = `https://www.linkedin.com/feed/update/urn:li:activity:${actId}/`;
              }
            }

            if (!postLink) {
              const linkEl = container.querySelector(
                'a[href*="/feed/update/urn:li:activity:"], a[href*="/posts/"], a[href*="/activity/"]'
              );
              if (linkEl) {
                const href = linkEl.getAttribute("href") || "";
                postLink = href.startsWith("http") ? href : `https://www.linkedin.com${href}`;
              }
            }

            // 2. Extract content text
            const textEl = container.querySelector(
              '.feed-shared-update-v2__description, .feed-shared-text, .update-components-text, span.break-words, .feed-shared-inline-show-more-text'
            );
            const rawText = (textEl?.textContent || "").trim();

            if (rawText && rawText.length > 10) {
              results.push({
                text: rawText,
                link: postLink,
              });
            }
          });

          return results;
        }, member.name);

        console.log(`  ✓ Found ${extracted.length} post(s) for ${member.name}.`);

        for (const item of extracted) {
          const cleanDescription = item.text.replace(/\s+/g, " ").trim();
          const firstLine = cleanDescription.split(". ")[0].trim();
          const title =
            firstLine.length > 85 ? firstLine.substring(0, 82) + "..." : firstLine || `${member.name} on LinkedIn`;

          let finalLink = item.link || member.linkedinUrl;
          if (!finalLink.includes("#author=")) {
            finalLink = `${finalLink}#author=${encodeURIComponent(member.name)}`;
          }

          posts.push({
            title,
            description: cleanDescription,
            link: finalLink,
            date: formatNewsDate(),
            author: member.name,
          });
        }
      } catch (err: any) {
        console.warn(`  Could not scrape posts for ${member.name}:`, err.message);
      }

      // 2s pause between profiles to avoid rate limits
      await page.waitForTimeout(2000);
    }
  } catch (err: any) {
    console.error("Headless scraper error:", err.message);
  } finally {
    if (browser) await browser.close();
  }

  return posts;
}

async function main() {
  console.log("==========================================");
  console.log("   InSilicoVida Multi-Person LinkedIn Sync");
  console.log("==========================================\n");

  const postsToProcess: RawPost[] = [];

  // 1. Automated Headless Scraper for Team Members if LINKEDIN_LI_AT is provided
  const liAtCookie = process.env.LINKEDIN_LI_AT;
  if (liAtCookie && liAtCookie.trim()) {
    try {
      const { data: dbMembers } = await supabase
        .from("team_members")
        .select("name, links");

      const membersToScrape = (dbMembers || [])
        .filter((m) => m.links?.LinkedIn && typeof m.links.LinkedIn === "string" && m.links.LinkedIn.trim())
        .map((m) => ({ name: m.name, linkedinUrl: m.links.LinkedIn.trim() }));

      if (membersToScrape.length > 0) {
        const scrapedPosts = await scrapeLinkedInTeamPosts(membersToScrape, liAtCookie);
        postsToProcess.push(...scrapedPosts);
      }
    } catch (err: any) {
      console.error("Error during automated member scraping:", err.message);
    }
  } else {
    console.log("ℹ️  LINKEDIN_LI_AT session cookie not set. Skipping automated profile scraping.");
    console.log("   (Add LINKEDIN_LI_AT secret in GitHub to automatically scrape team member posts every 6 hours)\n");
  }

  // 2. Process all configured feeds for different people
  const feedConfigs = await parseFeedConfigs();
  const singlePostUrl = process.env.LINKEDIN_POST_URL;
  const singlePostAuthor = process.env.LINKEDIN_AUTHOR;

  if (feedConfigs.length > 0) {
    console.log(`Found ${feedConfigs.length} configured feed(s):`);
    for (const feed of feedConfigs) {
      console.log(`- Fetching feed for "${feed.name}" from: ${feed.url}...`);
      try {
        const res = await fetch(feed.url, {
          headers: {
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) InSilicoVida-Sync/1.0",
          },
        });

        if (!res.ok) {
          console.error(`  Feed request failed with status: ${res.status}`);
        } else {
          const text = await res.text();
          const parsed = parseRssFeed(text, feed.name);
          console.log(`  ✓ Found ${parsed.length} posts for ${feed.name}.`);
          postsToProcess.push(...parsed);
        }
      } catch (err: any) {
        console.error(`  Error fetching feed for ${feed.name}:`, err.message);
      }
    }
  }

  // 2. Process single post URL if provided via env
  if (singlePostUrl) {
    console.log(`Extracting single post from: ${singlePostUrl} (Author: ${singlePostAuthor || "Team Member"})...`);
    const post = await fetchPostMetadata(singlePostUrl, singlePostAuthor);
    if (post) postsToProcess.push(post);
  }

  // 3. Fallback: Parse command-line args if supplied
  // Usage: npx tsx scripts/sync_linkedin.ts --url "https://..." --author "Deepika" --title "..." --desc "..."
  const args = process.argv.slice(2);
  const urlIdx = args.indexOf("--url");
  const authorIdx = args.indexOf("--author");
  const titleIdx = args.indexOf("--title");
  const descIdx = args.indexOf("--desc");

  if (urlIdx !== -1 && args[urlIdx + 1]) {
    const cliUrl = args[urlIdx + 1];
    const cliAuthor = authorIdx !== -1 ? args[authorIdx + 1] : undefined;
    const cliTitle = titleIdx !== -1 ? args[titleIdx + 1] : (cliAuthor ? `${cliAuthor} on LinkedIn` : "LinkedIn Update");
    const cliDesc = descIdx !== -1 ? args[descIdx + 1] : "Check out our latest update on LinkedIn.";

    let finalLink = cliUrl;
    if (cliAuthor && !finalLink.includes("#author=")) {
      finalLink = `${finalLink}#author=${encodeURIComponent(cliAuthor)}`;
    }

    postsToProcess.push({
      title: cliTitle,
      description: cliDesc,
      link: finalLink,
      date: formatNewsDate(),
      author: cliAuthor,
    });
  }

  if (postsToProcess.length === 0) {
    console.log("No LinkedIn posts found to sync.");
    console.log("\nMulti-Feed Configuration Options:");
    console.log("  LINKEDIN_FEEDS='[{\"name\":\"Dr. Vikas Kumar\",\"url\":\"https://...\"},{\"name\":\"Deepika\",\"url\":\"https://...\"}]'");
    console.log("  or LINKEDIN_FEEDS='Dr. Vikas Kumar=https://...,Deepika=https://...'");
    console.log("  or LINKEDIN_FEED_URL='https://...' LINKEDIN_AUTHOR='Deepika'");
    console.log("\nCLI Example:");
    console.log("  npx tsx scripts/sync_linkedin.ts --url \"https://linkedin.com/posts/...\" --author \"Deepika\" --title \"Title\" --desc \"Description\"");
    return;
  }

  // 4. Fetch existing news from Supabase for deduplication
  console.log("\nFetching existing news items from Supabase for deduplication...");
  const { data: existingNews, error: fetchErr } = await supabase
    .from("news")
    .select("id, title, link");

  if (fetchErr) {
    console.error("Failed to query existing news:", fetchErr.message);
    process.exit(1);
  }

  const existingBaseLinks = new Set(
    (existingNews || []).map((n) => getBaseLink(n.link)).filter(Boolean)
  );
  const existingTitles = new Set(
    (existingNews || []).map((n) => (n.title || "").trim().toLowerCase())
  );

  let insertedCount = 0;
  let skippedCount = 0;

  for (const post of postsToProcess) {
    const baseLinkKey = getBaseLink(post.link);
    const titleKey = (post.title || "").trim().toLowerCase();

    // Check if already in database
    if ((baseLinkKey && existingBaseLinks.has(baseLinkKey)) || existingTitles.has(titleKey)) {
      console.log(`[SKIP] Already exists: "${post.title}" (${post.link})`);
      skippedCount++;
      continue;
    }

    console.log(`[INSERT] Adding new post for ${post.author || "Lab"}: "${post.title}"...`);
    const { error: insertErr } = await supabase.from("news").insert([
      {
        date: post.date || formatNewsDate(),
        title: post.title,
        description: post.description,
        link: post.link || undefined,
      },
    ]);

    if (insertErr) {
      console.error(`  Error inserting: ${insertErr.message}`);
    } else {
      console.log(`  ✓ Successfully added.`);
      insertedCount++;
      if (baseLinkKey) existingBaseLinks.add(baseLinkKey);
      existingTitles.add(titleKey);
    }
  }

  console.log("\n==========================================");
  console.log(`Sync Complete!`);
  console.log(`Inserted: ${insertedCount} new news items.`);
  console.log(`Skipped:  ${skippedCount} existing items.`);
  console.log("==========================================");
}

main().catch((err) => {
  console.error("Fatal error during sync:", err);
  process.exit(1);
});
